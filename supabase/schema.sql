-- Password reset challenge tokens are one-time, short-lived, and stored hashed.
create table if not exists public.auth_password_reset_challenges (
  token_hash text primary key,
  email text not null,
  created_at double precision not null,
  expires_at double precision not null
);

create index if not exists idx_auth_password_reset_challenges_email
  on public.auth_password_reset_challenges(email);

alter table public.auth_password_reset_challenges enable row level security;
revoke all on table public.auth_password_reset_challenges from anon, authenticated;
grant all on table public.auth_password_reset_challenges to service_role;
