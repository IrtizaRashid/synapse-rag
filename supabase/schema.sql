-- OCR RAG auth tables
-- Run this in the Supabase dashboard: SQL Editor -> New query -> Run.
-- These are accessed only by the app backend via the service-role key.

create table if not exists auth_users (
  id            bigint generated by default as identity primary key,
  name          text not null,
  email         text not null unique,
  password_hash text not null,
  verified      boolean not null default false,
  created_at    double precision not null
);

create table if not exists auth_otp_codes (
  id          bigint generated by default as identity primary key,
  email       text not null,
  purpose     text not null check (purpose in ('signup', 'login')),
  code_hash   text not null,
  created_at  double precision not null,
  expires_at  double precision not null,
  attempts    integer not null default 0,
  lock_until  double precision not null default 0
);

create index if not exists auth_otp_email_idx on auth_otp_codes (email, purpose);

create table if not exists auth_sessions (
  token      text primary key,
  user_id    bigint not null references auth_users (id) on delete cascade,
  created_at double precision not null,
  expires_at double precision not null
);

create index if not exists auth_sessions_user_idx on auth_sessions (user_id);
create index if not exists auth_sessions_token_idx on auth_sessions (token);

