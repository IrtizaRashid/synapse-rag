-- Tenant-isolated semantic search tables for the Synapse workspace.
-- Safe to re-run after supabase/schema.sql.

create extension if not exists vector;

create table if not exists rag_chunks (
  id        bigint generated by default as identity primary key,
  source    text not null,
  location  text not null,
  text      text not null,
  embedding vector(768) not null,
  owner_id  bigint not null default 0
);

alter table rag_chunks add column if not exists owner_id bigint not null default 0;

create index if not exists rag_chunks_embedding_idx
  on rag_chunks using hnsw (embedding vector_cosine_ops);
create index if not exists rag_chunks_source_idx on rag_chunks (source);
create index if not exists rag_chunks_owner_source_idx on rag_chunks (owner_id, source);

-- Remove legacy global RPC overloads so PostgREST cannot select an unscoped
-- function accidentally.
drop function if exists search_chunks(vector(768), int, text[]);
drop function if exists list_rag_sources();

create or replace function search_chunks(
  query_embedding vector(768),
  top_k int default 5,
  sources text[] default null,
  owner bigint default 0
)
returns table (id bigint, source text, location text, text text, score double precision)
language plpgsql
stable
set search_path = public
as $$
begin
  return query
    select c.id, c.source, c.location, c.text,
           1 - (c.embedding <=> query_embedding) as score
    from rag_chunks c
    where c.owner_id = owner
      and (sources is null or c.source = any(sources))
    order by c.embedding <=> query_embedding
    limit top_k;
end;
$$;

revoke execute on function search_chunks(vector(768), int, text[], bigint) from public, anon, authenticated;
grant execute on function search_chunks(vector(768), int, text[], bigint) to service_role;

create or replace function list_rag_sources(owner bigint default 0)
returns table (source text, chunks bigint)
language sql
stable
set search_path = public
as $$
  select c.source, count(*)::bigint as chunks
  from rag_chunks c
  where c.owner_id = owner
  group by c.source
  order by lower(c.source);
$$;

revoke execute on function list_rag_sources(bigint) from public, anon, authenticated;
grant execute on function list_rag_sources(bigint) to service_role;
